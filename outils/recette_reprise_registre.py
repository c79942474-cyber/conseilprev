def demarrer():
    d, r = SOCLE + "/data", SOCLE + "/run"
    subprocess.run(["rm", "-rf", SOCLE], check=False)
    os.makedirs(d); os.makedirs(r)
    if os.geteuid() == 0:
        u = os.environ.get("RECETTE_PG_USER", "pgtest")
        subprocess.run(["chown", "-R", "%s:%s" % (u, u), SOCLE], check=False)
    os.chmod(d, 0o700)
    _su("%s -D %s -U postgres --auth=trust -E UTF8" % (_pg_bin("initdb"), d))
    _su('%s -D %s -o "-p 5433 -k %s -c listen_addresses=\'\'" -l %s/pg.log start'
        % (_pg_bin("pg_ctl"), d, r, SOCLE))
    for _ in range(40):
        if _su("%s -h %s -p 5433" % (_pg_bin("pg_isready"), r)).returncode == 0:
            break
        time.sleep(0.5)
    else:
        raise SystemExit("PostgreSQL n'a pas démarré. Voir %s/pg.log" % SOCLE)
    for base in ("src", "dst"):
        _su("psql -h %s -p 5433 -U postgres -c 'CREATE DATABASE %s'" % (r, base))


def arreter():
    _su("%s -D %s/data -m immediate stop" % (_pg_bin("pg_ctl"), SOCLE))
    subprocess.run(["rm", "-rf", SOCLE], check=False)


