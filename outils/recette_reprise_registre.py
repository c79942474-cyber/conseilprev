def _total(base):
    import psycopg
    with psycopg.connect(DSN % base) as c:
        return c.execute(
            "SELECT coalesce(sum((xpath('/row/c/text()', query_to_xml("
            "format('SELECT count(*) AS c FROM public.%I', relname), false, true, '')"
            "))[1]::text::bigint),0) FROM pg_class c JOIN pg_namespace n "
            "ON n.oid=c.relnamespace WHERE n.nspname='public' AND relkind='r'").fetchone()[0]


def _jouer(args=()):
    env = dict(os.environ, REGISTRE_ANCIEN_URL=URL % "src", DATABASE_URL=URL % "dst")
    p = subprocess.run([sys.executable, os.path.join(RACINE, "outils",
                                                     "reprise_registre.py")] + list(args),
                       capture_output=True, text=True, env=env, cwd=RACINE)
    return p.returncode, p.stdout


def _nombre(sortie, motif):
    m = re.search(motif, sortie)
    return int(m.group(1)) if m else None


