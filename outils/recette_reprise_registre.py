def _pg_bin(nom):
    for base in sorted(os.listdir("/usr/lib/postgresql"), reverse=True):
        p = "/usr/lib/postgresql/%s/bin/%s" % (base, nom)
        if os.path.exists(p):
            return p
    raise SystemExit("PostgreSQL introuvable sous /usr/lib/postgresql.")


